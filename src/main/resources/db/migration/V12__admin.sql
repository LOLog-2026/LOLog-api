-- 관리자: 오류 신고·의견, 정지 표시(LOLog-docs admin.md, db.md V9 초안)
-- 탈퇴하면 feedback.user_id만 NULL로 비운다(FR-AUTH-05의 예외).
CREATE TABLE feedback (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT,
    category VARCHAR(10) NOT NULL,
    text VARCHAR(1000) NOT NULL,
    app_version VARCHAR(30) NOT NULL,
    device_model VARCHAR(100) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT feedback_pk PRIMARY KEY (id),
    CONSTRAINT ck_feedback_category CHECK (category IN ('BUG', 'OPINION')),
    CONSTRAINT ck_feedback_status CHECK (status IN ('OPEN', 'DONE'))
);
CREATE INDEX idx_feedback_status_id ON feedback (status ASC, id DESC);
CREATE INDEX idx_feedback_user_id_created_at ON feedback (user_id ASC, created_at ASC);

-- 인증 서비스가 /internal/users/{id}/suspension으로 알려 준다. 방 멤버 목록의 "정지된 계정" 표시에 쓴다.
CREATE TABLE user_suspensions (
    user_id BIGINT NOT NULL,
    suspended_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_suspensions_pk PRIMARY KEY (user_id)
);

COMMENT ON TABLE feedback IS '오류 신고·의견-----사용자가 설정 화면에서 보냄. 하루 10번';
COMMENT ON COLUMN feedback.id IS '의견 ID';
COMMENT ON COLUMN feedback.user_id IS '보낸 회원 ID-----탈퇴하면 NULL';
COMMENT ON COLUMN feedback.category IS '종류-----BUG, OPINION';
COMMENT ON COLUMN feedback.text IS '내용-----1~1000자';
COMMENT ON COLUMN feedback.app_version IS '앱 버전';
COMMENT ON COLUMN feedback.device_model IS '기기 이름';
COMMENT ON COLUMN feedback.status IS '처리 상태-----OPEN, DONE';
COMMENT ON COLUMN feedback.created_at IS '생성 일시';
COMMENT ON COLUMN feedback.updated_at IS '수정 일시';
COMMENT ON TABLE user_suspensions IS '정지된 회원-----인증 서비스가 알려 줌. 기한이 지나면 정지 아님으로 봄';
COMMENT ON COLUMN user_suspensions.user_id IS '회원 ID';
COMMENT ON COLUMN user_suspensions.suspended_until IS '정지 기한-----NULL이면 영구';
COMMENT ON COLUMN user_suspensions.created_at IS '생성 일시';
