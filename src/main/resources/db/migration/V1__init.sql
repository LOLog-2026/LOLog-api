-- LOLog 메인 백엔드 — PostgreSQL DDL

CREATE TABLE recordings (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    client_recording_id VARCHAR(64) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT recordings_pk PRIMARY KEY (id),
    CONSTRAINT uk_recordings_user_id_client_recording_id UNIQUE (user_id, client_recording_id),
    CONSTRAINT ck_recordings_status CHECK (status IN ('RECEIVED', 'DETECTING', 'DONE', 'FAILED'))
);
CREATE TABLE recording_parts (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    recording_id BIGINT NOT NULL,
    part_no INTEGER NOT NULL,
    is_last BOOLEAN NOT NULL DEFAULT FALSE,
    duration_sec INTEGER NOT NULL,
    sentences JSON,
    carry_from_ms BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT recording_parts_pk PRIMARY KEY (id),
    CONSTRAINT uk_recording_parts_recording_id_part_no UNIQUE (recording_id, part_no),
    CONSTRAINT ck_recording_parts_status CHECK (status IN ('RECEIVED', 'DETECTING', 'DONE', 'FAILED')),
    CONSTRAINT ck_recording_parts_part_no CHECK (part_no >= 1)
);
CREATE TABLE cards (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    recording_id BIGINT,
    user_id BIGINT NOT NULL,
    kind VARCHAR(20) NOT NULL,
    summary TEXT NOT NULL,
    place VARCHAR(200),
    start_ms BIGINT NOT NULL,
    end_ms BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT cards_pk PRIMARY KEY (id),
    CONSTRAINT ck_cards_kind CHECK (kind IN ('웃김', '황당', '추억'))
);
CREATE TABLE card_speakers (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    card_id BIGINT NOT NULL,
    speaker_key VARCHAR(20) NOT NULL,
    name VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT card_speakers_pk PRIMARY KEY (id),
    CONSTRAINT uk_card_speakers_card_id_speaker_key UNIQUE (card_id, speaker_key)
);
CREATE TABLE card_lines (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    card_id BIGINT NOT NULL,
    line_no INTEGER NOT NULL,
    speaker_key VARCHAR(20) NOT NULL,
    text TEXT NOT NULL,
    start_ms BIGINT,
    end_ms BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT card_lines_pk PRIMARY KEY (id),
    CONSTRAINT uk_card_lines_card_id_line_no UNIQUE (card_id, line_no)
);
CREATE TABLE comics (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    card_id BIGINT,
    user_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'QUEUED',
    storyboard JSON,
    image_key VARCHAR(255),
    fail_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT comics_pk PRIMARY KEY (id),
    CONSTRAINT ck_comics_status CHECK (status IN ('QUEUED', 'STORYBOARD', 'DRAWING', 'DONE', 'FAILED'))
);
CREATE TABLE jobs (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    comic_id BIGINT,
    recording_part_id BIGINT,
    user_id BIGINT NOT NULL,
    job_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'QUEUED',
    attempts INTEGER NOT NULL DEFAULT 0,
    fail_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT jobs_pk PRIMARY KEY (id),
    CONSTRAINT ck_jobs_type CHECK (job_type IN ('DETECT', 'COMIC')),
    CONSTRAINT ck_jobs_status CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    CONSTRAINT ck_jobs_target CHECK ((job_type = 'DETECT' AND recording_part_id IS NOT NULL AND comic_id IS NULL) OR (job_type = 'COMIC' AND comic_id IS NOT NULL AND recording_part_id IS NULL))
);
CREATE TABLE device_tokens (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    token VARCHAR(512) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT device_tokens_pk PRIMARY KEY (id),
    CONSTRAINT uk_device_tokens_token UNIQUE (token)
);

ALTER TABLE recording_parts ADD CONSTRAINT fk_recording_parts_recordings FOREIGN KEY (recording_id) REFERENCES recordings (id) ON DELETE CASCADE;
ALTER TABLE cards ADD CONSTRAINT fk_cards_recordings FOREIGN KEY (recording_id) REFERENCES recordings (id) ON DELETE SET NULL;
ALTER TABLE card_speakers ADD CONSTRAINT fk_card_speakers_cards FOREIGN KEY (card_id) REFERENCES cards (id) ON DELETE CASCADE;
ALTER TABLE card_lines ADD CONSTRAINT fk_card_lines_cards FOREIGN KEY (card_id) REFERENCES cards (id) ON DELETE CASCADE;
ALTER TABLE comics ADD CONSTRAINT fk_comics_cards FOREIGN KEY (card_id) REFERENCES cards (id) ON DELETE SET NULL;
ALTER TABLE jobs ADD CONSTRAINT fk_jobs_recording_parts FOREIGN KEY (recording_part_id) REFERENCES recording_parts (id) ON DELETE CASCADE;
ALTER TABLE jobs ADD CONSTRAINT fk_jobs_comics FOREIGN KEY (comic_id) REFERENCES comics (id) ON DELETE CASCADE;

CREATE INDEX idx_recording_parts_recording_id ON recording_parts (recording_id ASC);
CREATE INDEX idx_cards_user_id_id ON cards (user_id ASC, id DESC);
CREATE INDEX idx_cards_recording_id ON cards (recording_id ASC);
CREATE INDEX idx_card_speakers_card_id ON card_speakers (card_id ASC);
CREATE INDEX idx_card_lines_card_id ON card_lines (card_id ASC);
CREATE INDEX idx_comics_user_id_id ON comics (user_id ASC, id DESC);
CREATE INDEX idx_comics_card_id ON comics (card_id ASC);
CREATE UNIQUE INDEX uk_comics_card_id_in_progress ON comics (card_id ASC) WHERE status IN ('QUEUED', 'STORYBOARD', 'DRAWING');
CREATE INDEX idx_jobs_user_id ON jobs (user_id ASC);
CREATE INDEX idx_jobs_recording_part_id ON jobs (recording_part_id ASC);
CREATE INDEX idx_jobs_comic_id ON jobs (comic_id ASC);
CREATE INDEX idx_device_tokens_user_id ON device_tokens (user_id ASC);

