-- 블로그 글로 카드 만들기(LOLog-docs texts.md 7장, FR-TEXT-02·03).
CREATE TABLE blog_sources (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    site_url VARCHAR(500) NOT NULL,
    title VARCHAR(200),
    feed_url VARCHAR(500) NOT NULL,
    categories JSONB NOT NULL DEFAULT '[]',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT blog_sources_pk PRIMARY KEY (id),
    CONSTRAINT uk_blog_sources_user_id_feed_url UNIQUE (user_id, feed_url)
);
CREATE INDEX idx_blog_sources_user_id ON blog_sources (user_id ASC);

-- 같은 글을 다시 가져오지 않게 카드를 지워도, 연결을 끊어도 남긴다.
CREATE TABLE blog_posts (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    source_id BIGINT,
    user_id BIGINT NOT NULL,
    guid VARCHAR(500) NOT NULL,
    title VARCHAR(300) NOT NULL,
    link VARCHAR(500) NOT NULL,
    category VARCHAR(100),
    published_at TIMESTAMPTZ,
    blog_title VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT blog_posts_pk PRIMARY KEY (id),
    CONSTRAINT uk_blog_posts_user_id_guid UNIQUE (user_id, guid)
);
ALTER TABLE blog_posts ADD CONSTRAINT fk_blog_posts_blog_sources FOREIGN KEY (source_id) REFERENCES blog_sources (id) ON DELETE SET NULL;
CREATE INDEX idx_blog_posts_source_id_id ON blog_posts (source_id ASC, id DESC);

-- blog_posts는 탈퇴 때만 지워지고 그때 texts를 먼저 지운다. SET NULL이면 ck_texts_blog_post와 부딪혀서 기본(NO ACTION)으로 둔다.
ALTER TABLE texts ADD CONSTRAINT fk_texts_blog_posts FOREIGN KEY (blog_post_id) REFERENCES blog_posts (id);
CREATE INDEX idx_texts_blog_post_id ON texts (blog_post_id ASC);

COMMENT ON TABLE blog_sources IS '블로그-----사용자가 연결한 블로그(RSS 하나)';
COMMENT ON COLUMN blog_sources.id IS '블로그 ID';
COMMENT ON COLUMN blog_sources.user_id IS '회원 ID';
COMMENT ON COLUMN blog_sources.site_url IS '블로그 주소-----사용자가 넣은 주소';
COMMENT ON COLUMN blog_sources.title IS '블로그 이름-----RSS channel의 title';
COMMENT ON COLUMN blog_sources.feed_url IS 'RSS 주소-----서버가 찾은 주소';
COMMENT ON COLUMN blog_sources.categories IS '가져올 카테고리-----문자열 배열. 비면 전체';
COMMENT ON COLUMN blog_sources.created_at IS '생성 일시';
COMMENT ON TABLE blog_posts IS '블로그 글-----가져온 글. 카드를 지워도, 연결을 끊어도 남음';
COMMENT ON COLUMN blog_posts.id IS '블로그 글 ID';
COMMENT ON COLUMN blog_posts.source_id IS '블로그 ID-----연결을 끊으면 NULL';
COMMENT ON COLUMN blog_posts.user_id IS '회원 ID';
COMMENT ON COLUMN blog_posts.guid IS '글 구분 값-----RSS guid, Atom id, 둘 다 없으면 link';
COMMENT ON COLUMN blog_posts.title IS '글 제목';
COMMENT ON COLUMN blog_posts.link IS '원문 링크';
COMMENT ON COLUMN blog_posts.category IS '카테고리-----고른 카테고리 중 맞은 것';
COMMENT ON COLUMN blog_posts.published_at IS '쓴 시각-----RSS pubDate. 없으면 NULL';
COMMENT ON COLUMN blog_posts.blog_title IS '블로그 이름-----가져올 때 복사(연결을 끊어도 남게)';
COMMENT ON COLUMN blog_posts.created_at IS '가져온 시각';
