-- 카드 영상(LOLog-docs video.md, FR-EXT-02). 명세에 DB가 없어 만화(comics)와 같은 방식으로 정한 초안이다.
-- 작업은 두 단계다: 3호가 목소리(VIDEO_VOICE), 2호가 그림·합치기(VIDEO_DRAW). 단계마다 jobs 한 줄이다.
CREATE TABLE videos (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    card_id BIGINT,
    user_id BIGINT NOT NULL,
    card_summary VARCHAR(30),
    status VARCHAR(10) NOT NULL DEFAULT 'QUEUED',
    storyboard JSONB,
    audio_key VARCHAR(255),
    video_key VARCHAR(255),
    thumb_key VARCHAR(255),
    duration_ms BIGINT,
    fail_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT videos_pk PRIMARY KEY (id),
    CONSTRAINT ck_videos_status CHECK (status IN ('QUEUED', 'VOICE', 'DRAWING', 'DONE', 'FAILED'))
);
ALTER TABLE videos ADD CONSTRAINT fk_videos_cards FOREIGN KEY (card_id) REFERENCES cards (id) ON DELETE SET NULL;
-- 한 카드에 만드는 중인 영상은 하나(VIDEO_IN_PROGRESS)
CREATE UNIQUE INDEX uk_videos_card_id_in_progress ON videos (card_id) WHERE status IN ('QUEUED', 'VOICE', 'DRAWING');
CREATE INDEX idx_videos_user_id_id ON videos (user_id ASC, id DESC);
CREATE INDEX idx_videos_card_id ON videos (card_id ASC);

-- 카드 하나에 실패가 아닌 영상 2개까지. 만화의 comic_count처럼 지워도 돌아오지 않고, 실패하면 돌아온다.
ALTER TABLE cards ADD COLUMN video_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE cards ADD CONSTRAINT ck_cards_video_count CHECK (video_count BETWEEN 0 AND 2);

ALTER TABLE jobs ADD COLUMN video_id BIGINT;
ALTER TABLE jobs ADD CONSTRAINT fk_jobs_videos FOREIGN KEY (video_id) REFERENCES videos (id) ON DELETE CASCADE;
CREATE INDEX idx_jobs_video_id ON jobs (video_id ASC);
ALTER TABLE jobs DROP CONSTRAINT ck_jobs_type;
ALTER TABLE jobs ADD CONSTRAINT ck_jobs_type CHECK (job_type IN ('DETECT', 'COMIC', 'AVATAR', 'VIDEO_VOICE', 'VIDEO_DRAW'));
ALTER TABLE jobs DROP CONSTRAINT ck_jobs_target;
ALTER TABLE jobs ADD CONSTRAINT ck_jobs_target CHECK (
    (job_type = 'DETECT' AND recording_part_id IS NOT NULL AND comic_id IS NULL AND video_id IS NULL)
    OR (job_type = 'COMIC' AND comic_id IS NOT NULL AND recording_part_id IS NULL AND video_id IS NULL)
    OR (job_type = 'AVATAR' AND comic_id IS NULL AND recording_part_id IS NULL AND video_id IS NULL)
    OR (job_type IN ('VIDEO_VOICE', 'VIDEO_DRAW') AND video_id IS NOT NULL AND comic_id IS NULL AND recording_part_id IS NULL));

COMMENT ON TABLE videos IS '카드 영상-----카드로 만든 30초 안팎의 세로 영상(TTS 쇼츠). 카드를 지워도 남음';
COMMENT ON COLUMN videos.id IS '영상 ID';
COMMENT ON COLUMN videos.card_id IS '카드 ID-----카드를 지우면 NULL';
COMMENT ON COLUMN videos.user_id IS '회원 ID';
COMMENT ON COLUMN videos.card_summary IS '카드 요약-----요청할 때 카드의 summary를 복사(만화와 같음). 카드를 지워도 목록 제목으로 씀';
COMMENT ON COLUMN videos.status IS '상태-----QUEUED, VOICE, DRAWING, DONE, FAILED';
COMMENT ON COLUMN videos.storyboard IS '영상 콘티-----3호가 보낸 JSON 그대로. 2호가 받아 감';
COMMENT ON COLUMN videos.audio_key IS '대사 음성 파일 키-----중간 파일. DONE·FAILED가 되면 지움';
COMMENT ON COLUMN videos.video_key IS '완성 영상 키-----users/{userId}/videos/{videoId}/video.mp4';
COMMENT ON COLUMN videos.thumb_key IS '목록용 그림 키-----users/{userId}/videos/{videoId}/thumb.jpg';
COMMENT ON COLUMN videos.duration_ms IS '영상 길이(ms)';
COMMENT ON COLUMN videos.fail_reason IS '실패 이유';
COMMENT ON COLUMN videos.created_at IS '생성 일시';
COMMENT ON COLUMN videos.updated_at IS '수정 일시';
COMMENT ON COLUMN cards.video_count IS '영상 만들기 횟수-----실패하면 줄고 지워도 그대로. 2까지';
COMMENT ON COLUMN jobs.video_id IS '영상 ID-----VIDEO_VOICE, VIDEO_DRAW 작업';
