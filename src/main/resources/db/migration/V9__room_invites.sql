-- 지금 있는 방은 만든 사람을 방장으로 채운다.
ALTER TABLE rooms ADD COLUMN owner_id BIGINT;
UPDATE rooms SET owner_id = created_by;
ALTER TABLE rooms ALTER COLUMN owner_id SET NOT NULL;

CREATE TABLE room_invites (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    invited_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT room_invites_pk PRIMARY KEY (id),
    CONSTRAINT uk_room_invites_room_id_user_id UNIQUE (room_id, user_id)
);
ALTER TABLE room_invites ADD CONSTRAINT fk_room_invites_rooms FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE;
CREATE INDEX idx_room_invites_user_id ON room_invites (user_id ASC);

COMMENT ON COLUMN rooms.owner_id IS '방장 회원 ID-----처음엔 만든 사람. 나가면 새 방장으로 바뀜(외래 키 아님)';
COMMENT ON TABLE room_invites IS '방 초대-----답을 기다리는 초대. 수락·거절·취소하면 줄을 지움. 인원은 멤버 + 초대로 셈';
COMMENT ON COLUMN room_invites.id IS '초대 ID';
COMMENT ON COLUMN room_invites.room_id IS '방 ID';
COMMENT ON COLUMN room_invites.user_id IS '초대받은 회원 ID';
COMMENT ON COLUMN room_invites.invited_by IS '보낸 방장 회원 ID';
COMMENT ON COLUMN room_invites.created_at IS '생성 일시-----초대한 시각';
