-- 글로 카드 만들기(LOLog-docs texts.md 7장, FR-TEXT-01). 직접 쓴 글과 블로그 글이 같은 표를 쓴다.
-- 블로그 표(blog_sources·blog_posts)와 texts.blog_post_id 외래 키는 V16에서 더한다.
CREATE TABLE texts (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    source VARCHAR(10) NOT NULL,
    blog_post_id BIGINT,
    title VARCHAR(300) NOT NULL,
    body TEXT,
    place VARCHAR(200),
    situation VARCHAR(500),
    truncated BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT texts_pk PRIMARY KEY (id),
    CONSTRAINT ck_texts_source CHECK (source IN ('BLOG', 'WRITTEN')),
    CONSTRAINT ck_texts_blog_post CHECK ((source = 'BLOG') = (blog_post_id IS NOT NULL))
);
CREATE INDEX idx_texts_user_id ON texts (user_id ASC);

-- 카드: 녹음 카드는 recording_id, 글 카드는 text_id. 글 카드는 시간 값이 없다.
ALTER TABLE cards ADD COLUMN text_id BIGINT;
ALTER TABLE cards ALTER COLUMN start_ms DROP NOT NULL;
ALTER TABLE cards ALTER COLUMN end_ms DROP NOT NULL;
CREATE INDEX idx_cards_text_id ON cards (text_id);
ALTER TABLE cards ADD CONSTRAINT fk_cards_texts FOREIGN KEY (text_id) REFERENCES texts (id) ON DELETE SET NULL;
-- 녹음과 글을 동시에 가리키지 않는다. 녹음을 지워 recording_id가 NULL이 된 카드도 통과한다.
ALTER TABLE cards ADD CONSTRAINT ck_cards_origin CHECK (recording_id IS NULL OR text_id IS NULL);

-- 작업: TEXT는 글 하나(text_id)를 카드로 만든다.
ALTER TABLE jobs ADD COLUMN text_id BIGINT;
ALTER TABLE jobs ADD CONSTRAINT fk_jobs_texts FOREIGN KEY (text_id) REFERENCES texts (id) ON DELETE CASCADE;
CREATE INDEX idx_jobs_text_id ON jobs (text_id ASC);
ALTER TABLE jobs DROP CONSTRAINT ck_jobs_type;
ALTER TABLE jobs ADD CONSTRAINT ck_jobs_type CHECK (job_type IN ('DETECT', 'COMIC', 'AVATAR', 'VIDEO_VOICE', 'VIDEO_DRAW', 'TEXT'));
ALTER TABLE jobs DROP CONSTRAINT ck_jobs_target;
ALTER TABLE jobs ADD CONSTRAINT ck_jobs_target CHECK (
    (job_type = 'DETECT' AND recording_part_id IS NOT NULL AND comic_id IS NULL AND video_id IS NULL AND text_id IS NULL)
    OR (job_type = 'COMIC' AND comic_id IS NOT NULL AND recording_part_id IS NULL AND video_id IS NULL AND text_id IS NULL)
    OR (job_type = 'AVATAR' AND comic_id IS NULL AND recording_part_id IS NULL AND video_id IS NULL AND text_id IS NULL)
    OR (job_type IN ('VIDEO_VOICE', 'VIDEO_DRAW') AND video_id IS NOT NULL AND comic_id IS NULL AND recording_part_id IS NULL AND text_id IS NULL)
    OR (job_type = 'TEXT' AND text_id IS NOT NULL AND comic_id IS NULL AND recording_part_id IS NULL AND video_id IS NULL));

COMMENT ON TABLE texts IS '글-----카드로 만들 글(직접 쓴 글·블로그 글). 카드를 지우면 함께 지움';
COMMENT ON COLUMN texts.id IS '글 ID';
COMMENT ON COLUMN texts.user_id IS '회원 ID';
COMMENT ON COLUMN texts.source IS '출처-----WRITTEN(직접 쓴 글), BLOG(블로그 글)';
COMMENT ON COLUMN texts.blog_post_id IS '블로그 글 ID-----블로그 글이면 있음';
COMMENT ON COLUMN texts.title IS '제목';
COMMENT ON COLUMN texts.body IS '본문-----블로그 글은 카드가 생기면 NULL로 비움';
COMMENT ON COLUMN texts.place IS '장소-----적으면 카드 장소가 됨';
COMMENT ON COLUMN texts.situation IS '상황-----LLM에 배경으로만 넘김';
COMMENT ON COLUMN texts.truncated IS '잘림-----길어서 앞부분만 썼는지. 직접 쓴 글은 늘 false';
COMMENT ON COLUMN texts.created_at IS '생성 일시';
COMMENT ON COLUMN cards.text_id IS '글 ID-----글 카드만 있음';
COMMENT ON COLUMN jobs.text_id IS '글 ID-----TEXT 작업';
