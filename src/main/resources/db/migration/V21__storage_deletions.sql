-- 지울 저장소 파일 목록. 데이터를 바꾸는 트랜잭션 안에서 줄을 넣어 그 변경과 함께 커밋·되돌림된다.
-- 커밋 뒤에 바로 한 번 지우고, 지우면 줄을 뺀다. 실패한 줄은 주기 작업이 다시 지운다.
-- 사람마다의 데이터를 가리키지 않아(키만 있음) 탈퇴로 지우지 않는다. 탈퇴는 users/{userId}/를 따로 지운다.
CREATE TABLE storage_deletions (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    object_key VARCHAR(255) NOT NULL,
    prefix BOOLEAN NOT NULL DEFAULT false,
    attempts INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error VARCHAR(200),
    CONSTRAINT storage_deletions_pk PRIMARY KEY (id)
);
-- 다시 지우기는 덜 실패한 줄, 오래된 줄부터 읽는다.
CREATE INDEX idx_storage_deletions_attempts_id ON storage_deletions (attempts ASC, id ASC);
-- 같은 키에 파일을 다시 올리기 전에 그 키의 지우기를 뺀다.
CREATE INDEX idx_storage_deletions_object_key ON storage_deletions (object_key ASC);

COMMENT ON TABLE storage_deletions IS '지울 저장소 파일-----커밋 뒤 지우기를 실패하면 남아 주기 작업이 다시 지움';
COMMENT ON COLUMN storage_deletions.id IS '지우기 ID';
COMMENT ON COLUMN storage_deletions.object_key IS '저장소 키-----prefix가 true면 이 글자로 시작하는 키를 모두 지움';
COMMENT ON COLUMN storage_deletions.prefix IS '접두어 여부-----true면 object_key 아래를 모두 지움';
COMMENT ON COLUMN storage_deletions.attempts IS '실패한 횟수';
COMMENT ON COLUMN storage_deletions.created_at IS '생성 일시';
COMMENT ON COLUMN storage_deletions.last_error IS '마지막 실패 이유-----예외 종류와 저장소 오류 코드만. 실패한 적 없으면 NULL';
