-- 알림 목록과 공지사항, 앱 안 새 소식 표시(LOLog-docs inbox.md, db.md V9 초안)
CREATE TABLE notices (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(100) NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notices_pk PRIMARY KEY (id)
);
CREATE TABLE notifications (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    type VARCHAR(30) NOT NULL,
    data JSONB NOT NULL,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notifications_pk PRIMARY KEY (id)
);
CREATE INDEX idx_notifications_user_id_id ON notifications (user_id ASC, id DESC);
CREATE INDEX idx_notifications_created_at ON notifications (created_at ASC);
CREATE TABLE notice_reads (
    notice_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notice_reads_pk PRIMARY KEY (notice_id, user_id)
);
ALTER TABLE notice_reads ADD CONSTRAINT fk_notice_reads_notices FOREIGN KEY (notice_id) REFERENCES notices (id) ON DELETE CASCADE;
CREATE INDEX idx_notice_reads_user_id ON notice_reads (user_id ASC);
CREATE TABLE badge_reads (
    user_id BIGINT NOT NULL,
    kind VARCHAR(20) NOT NULL,
    seen_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT badge_reads_pk PRIMARY KEY (user_id, kind)
);

COMMENT ON TABLE notices IS '공지사항-----모든 사용자에게 같은 글. 관리자가 씀';
COMMENT ON COLUMN notices.id IS '공지사항 ID';
COMMENT ON COLUMN notices.title IS '제목-----1~100자';
COMMENT ON COLUMN notices.body IS '본문';
COMMENT ON COLUMN notices.created_at IS '생성 일시';
COMMENT ON COLUMN notices.updated_at IS '수정 일시';
COMMENT ON TABLE notifications IS '알림-----푸시를 보낼 때 같은 내용을 한 줄 남김. 30일 지나면 지움';
COMMENT ON COLUMN notifications.id IS '알림 ID';
COMMENT ON COLUMN notifications.user_id IS '받은 회원 ID';
COMMENT ON COLUMN notifications.type IS '종류-----푸시 type 그대로';
COMMENT ON COLUMN notifications.data IS '값-----푸시에 넣은 값 그대로(type 뺌, 대사 없음)';
COMMENT ON COLUMN notifications.read_at IS '읽은 시각-----NULL이면 안 읽음';
COMMENT ON COLUMN notifications.created_at IS '생성 일시';
COMMENT ON TABLE notice_reads IS '공지사항 읽음-----회원마다 읽은 공지사항';
COMMENT ON COLUMN notice_reads.notice_id IS '공지사항 ID';
COMMENT ON COLUMN notice_reads.user_id IS '회원 ID';
COMMENT ON COLUMN notice_reads.read_at IS '읽은 시각';
COMMENT ON TABLE badge_reads IS '새 소식 표시를 마지막으로 본 시각-----기능 화면을 연 시각';
COMMENT ON COLUMN badge_reads.user_id IS '회원 ID';
COMMENT ON COLUMN badge_reads.kind IS '기능-----cards, comics, profileCharacter, rooms';
COMMENT ON COLUMN badge_reads.seen_at IS '그 화면을 마지막으로 연 시각';
