-- 쇼츠 효과음·배경음(LOLog-docs sounds.md 5장, FR-EXT-03). Freesound CC0 소리를 미리 모아 두고, 콘티가 고른 검색어 값으로 찾는다.
-- 사람마다의 데이터가 아니라서 탈퇴로 지우지 않는다.
CREATE TABLE sound_library (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    kind VARCHAR(5) NOT NULL,
    query VARCHAR(30) NOT NULL,
    title VARCHAR(200),
    object_key VARCHAR(255) NOT NULL,
    duration_ms INT NOT NULL,
    freesound_id BIGINT NOT NULL,
    source_url VARCHAR(500) NOT NULL,
    license VARCHAR(10) NOT NULL DEFAULT 'CC0',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT sound_library_pk PRIMARY KEY (id),
    CONSTRAINT uk_sound_library_freesound_id UNIQUE (freesound_id),
    CONSTRAINT ck_sound_library_kind CHECK (kind IN ('SFX', 'BGM')),
    CONSTRAINT ck_sound_library_license CHECK (license = 'CC0')
);
CREATE INDEX idx_sound_library_kind_query ON sound_library (kind ASC, query ASC);

COMMENT ON TABLE sound_library IS '효과음·배경음-----Freesound에서 모은 CC0 소리';
COMMENT ON COLUMN sound_library.id IS '소리 ID';
COMMENT ON COLUMN sound_library.kind IS '종류-----SFX(효과음), BGM(배경음)';
COMMENT ON COLUMN sound_library.query IS '검색어 값-----door_slam 등. 콘티가 고르는 값과 같음';
COMMENT ON COLUMN sound_library.title IS 'Freesound 제목';
COMMENT ON COLUMN sound_library.object_key IS '저장소 키-----defaults/sounds/{id}.ogg';
COMMENT ON COLUMN sound_library.duration_ms IS '길이(ms)';
COMMENT ON COLUMN sound_library.freesound_id IS 'Freesound 소리 ID-----같은 소리를 두 번 넣지 않게';
COMMENT ON COLUMN sound_library.source_url IS '출처-----Freesound 페이지';
COMMENT ON COLUMN sound_library.license IS '라이선스-----CC0만';
COMMENT ON COLUMN sound_library.created_at IS '생성 일시';
