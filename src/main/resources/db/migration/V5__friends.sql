-- 친구 등록: 회원 프로필, 친구 관계·요청, 차단
CREATE TABLE user_profiles (
    user_id BIGINT NOT NULL,
    nickname VARCHAR(10),
    friend_code VARCHAR(8) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_profiles_pk PRIMARY KEY (user_id),
    CONSTRAINT uk_user_profiles_friend_code UNIQUE (friend_code)
);
CREATE TABLE friendships (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    requester_id BIGINT NOT NULL,
    addressee_id BIGINT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT friendships_pk PRIMARY KEY (id),
    CONSTRAINT ck_friendships_status CHECK (status IN ('PENDING', 'ACCEPTED')),
    CONSTRAINT ck_friendships_not_self CHECK (requester_id <> addressee_id)
);
CREATE TABLE user_blocks (
    blocker_id BIGINT NOT NULL,
    blocked_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_blocks_pk PRIMARY KEY (blocker_id, blocked_id),
    CONSTRAINT ck_user_blocks_not_self CHECK (blocker_id <> blocked_id)
);

CREATE UNIQUE INDEX uk_friendships_pair ON friendships (LEAST(requester_id, addressee_id), GREATEST(requester_id, addressee_id));
CREATE INDEX idx_friendships_addressee_id_status ON friendships (addressee_id ASC, status ASC);
CREATE INDEX idx_friendships_requester_id_status ON friendships (requester_id ASC, status ASC);
CREATE INDEX idx_user_blocks_blocked_id ON user_blocks (blocked_id ASC);

COMMENT ON TABLE user_profiles IS '회원 프로필-----닉네임과 친구 코드. 처음 프로필을 볼 때 만들어짐';
COMMENT ON COLUMN user_profiles.user_id IS '회원 ID-----인증 DB 회원 ID(외래 키 아님)';
COMMENT ON COLUMN user_profiles.nickname IS '닉네임-----1~10자. 아직 안 정했으면 NULL. 겹쳐도 됨';
COMMENT ON COLUMN user_profiles.friend_code IS '친구 코드-----대문자·숫자 8자리(0·O·1·I·L 제외). 프로필을 만들 때 서버가 발급하고 바뀌지 않음';
COMMENT ON COLUMN user_profiles.created_at IS '생성 일시';
COMMENT ON COLUMN user_profiles.updated_at IS '수정 일시';
COMMENT ON TABLE friendships IS '친구 관계-----친구 요청과 친구. 두 사람 사이에 줄 하나. 거절·취소·끊기는 줄을 지움';
COMMENT ON COLUMN friendships.id IS '친구 관계 ID';
COMMENT ON COLUMN friendships.requester_id IS '요청한 회원 ID';
COMMENT ON COLUMN friendships.addressee_id IS '요청받은 회원 ID';
COMMENT ON COLUMN friendships.status IS '상태-----PENDING(요청 중), ACCEPTED(친구)';
COMMENT ON COLUMN friendships.created_at IS '생성 일시-----요청한 시각';
COMMENT ON COLUMN friendships.updated_at IS '수정 일시-----ACCEPTED가 된 뒤에는 친구가 된 시각';
COMMENT ON TABLE user_blocks IS '차단-----차단한 사람과 차단된 사람';
COMMENT ON COLUMN user_blocks.blocker_id IS '차단한 회원 ID';
COMMENT ON COLUMN user_blocks.blocked_id IS '차단된 회원 ID';
COMMENT ON COLUMN user_blocks.created_at IS '생성 일시-----차단한 시각';
