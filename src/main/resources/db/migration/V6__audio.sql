-- 음성 저장·순간 다시 듣기
CREATE TABLE recording_audio_files (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    recording_id BIGINT NOT NULL,
    seq INTEGER NOT NULL,
    audio_key VARCHAR(255) NOT NULL,
    start_ms BIGINT NOT NULL,
    end_ms BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT recording_audio_files_pk PRIMARY KEY (id),
    CONSTRAINT uk_recording_audio_files_recording_id_seq UNIQUE (recording_id, seq),
    CONSTRAINT ck_recording_audio_files_seq CHECK (seq >= 1),
    CONSTRAINT ck_recording_audio_files_range CHECK (start_ms >= 0 AND start_ms < end_ms)
);
ALTER TABLE recording_audio_files ADD CONSTRAINT fk_recording_audio_files_recordings FOREIGN KEY (recording_id) REFERENCES recordings (id) ON DELETE CASCADE;

ALTER TABLE recordings ADD COLUMN ended_at TIMESTAMPTZ;
ALTER TABLE recordings ADD COLUMN audio_saved BOOLEAN NOT NULL DEFAULT FALSE;
-- 이미 있는 녹음: 시작 시각에 받은 묶음 길이를 더해 채운다
UPDATE recordings r SET ended_at = r.started_at + make_interval(secs => COALESCE(
    (SELECT SUM(p.duration_sec) FROM recording_parts p WHERE p.recording_id = r.id), 0));

ALTER TABLE cards ADD COLUMN audio_key VARCHAR(255);
ALTER TABLE cards ADD COLUMN audio_duration_ms BIGINT;
ALTER TABLE cards ADD CONSTRAINT ck_cards_audio CHECK ((audio_key IS NULL) = (audio_duration_ms IS NULL));

COMMENT ON TABLE recordings IS '녹음-----녹음 하나(최장 3시간). 글은 묶음(recording_parts)에, 음성은 음성 파일(recording_audio_files)에 있음';
COMMENT ON TABLE recording_audio_files IS '녹음 음성 파일-----10분 단위로 올라온 전체 녹음 파일. 녹음이 끝난 때부터 7일 뒤 파일과 함께 지움';
COMMENT ON COLUMN recording_audio_files.id IS '음성 파일 ID';
COMMENT ON COLUMN recording_audio_files.recording_id IS '녹음 ID';
COMMENT ON COLUMN recording_audio_files.seq IS '파일 번호-----녹음 안에서 1부터. 글 묶음 번호와 따로 감';
COMMENT ON COLUMN recording_audio_files.audio_key IS '음성 오브젝트 키';
COMMENT ON COLUMN recording_audio_files.start_ms IS '시작 시각(ms)-----녹음 시작부터';
COMMENT ON COLUMN recording_audio_files.end_ms IS '끝 시각(ms)';
COMMENT ON COLUMN recording_audio_files.created_at IS '생성 일시';
COMMENT ON COLUMN recording_audio_files.updated_at IS '수정 일시-----같은 번호를 다시 올리면 바뀜';
COMMENT ON COLUMN recordings.ended_at IS '녹음 끝 시각-----시작 시각 + 받은 묶음 길이의 합. 묶음을 받을 때마다 고쳐 적음. 7일을 세는 기준';
COMMENT ON COLUMN recordings.audio_saved IS '음성 저장 여부-----이 녹음에서 음성 저장을 켰는지. 글 묶음을 올릴 때 받음';
COMMENT ON COLUMN cards.audio_key IS '카드 구간 음성 오브젝트 키-----음성이 없으면 NULL. 카드를 지울 때 파일도 지움';
COMMENT ON COLUMN cards.audio_duration_ms IS '카드 구간 음성 길이(ms)-----앞뒤 여유 0.5초씩 포함';
