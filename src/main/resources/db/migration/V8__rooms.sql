-- 친구와 같이 쓰는 방: 방, 멤버, 올린 만화, 좋아요, 대화
CREATE TABLE rooms (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(20) NOT NULL,
    created_by BIGINT NOT NULL,
    last_activity_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT rooms_pk PRIMARY KEY (id)
);
CREATE TABLE room_members (
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    last_read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT room_members_pk PRIMARY KEY (room_id, user_id)
);
CREATE TABLE room_posts (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    room_id BIGINT NOT NULL,
    comic_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT room_posts_pk PRIMARY KEY (id),
    CONSTRAINT uk_room_posts_room_id_comic_id UNIQUE (room_id, comic_id)
);
CREATE TABLE room_post_likes (
    post_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT room_post_likes_pk PRIMARY KEY (post_id, user_id)
);
CREATE TABLE room_messages (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    message_type VARCHAR(10) NOT NULL,
    post_id BIGINT,
    body VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT room_messages_pk PRIMARY KEY (id),
    CONSTRAINT ck_room_messages_type CHECK (message_type IN ('CREATED', 'POSTED', 'LIKED', 'COMMENT')),
    CONSTRAINT ck_room_messages_body CHECK ((message_type = 'COMMENT') = (body IS NOT NULL)),
    CONSTRAINT ck_room_messages_post CHECK (message_type IN ('CREATED', 'COMMENT') OR post_id IS NOT NULL)
);

